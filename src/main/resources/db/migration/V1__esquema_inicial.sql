-- AlocaSenac: esquema operacional inicial (docs/arquitetura.md §15)

CREATE TABLE recurso (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nome        VARCHAR(255),
    tipo        VARCHAR(255),
    capacidade  INTEGER,
    localizacao VARCHAR(255),
    restrito    BOOLEAN NOT NULL
);

CREATE TABLE reserva (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante VARCHAR(255),
    inicio      TIMESTAMP(6) WITH TIME ZONE,
    fim         TIMESTAMP(6) WITH TIME ZONE,
    estado      VARCHAR(255)
);

CREATE TABLE reserva_recurso_ids (
    reserva_id  BIGINT NOT NULL REFERENCES reserva (id),
    recurso_ids BIGINT
);

-- Ocupação de recurso por reserva ou bloqueio (ADR-003)
CREATE TABLE ocupacao (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    recurso_id    BIGINT,
    referencia_id BIGINT,
    inicio        TIMESTAMP(6) WITH TIME ZONE,
    fim           TIMESTAMP(6) WITH TIME ZONE,
    origem        VARCHAR(255),
    ativa         BOOLEAN NOT NULL
);

-- I-4 / ADR-003: nenhuma ocupação ativa do mesmo recurso se sobrepõe, garantido pelo banco.
-- Intervalo semiaberto '[)' (decisão D-01). Só ocupações de RESERVA por enquanto:
-- o bloqueio por manutenção (RF8, RN-T4) entra no ciclo BDD (B3).
CREATE EXTENSION IF NOT EXISTS btree_gist;

ALTER TABLE ocupacao
    ADD CONSTRAINT ocupacao_sem_sobreposicao
    EXCLUDE USING gist (recurso_id WITH =, tstzrange(inicio, fim, '[)') WITH &&)
    WHERE (ativa AND origem = 'RESERVA');

CREATE TABLE tentativa_recusada (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    solicitante VARCHAR(255),
    recurso_id  BIGINT,
    inicio      TIMESTAMP(6) WITH TIME ZONE,
    fim         TIMESTAMP(6) WITH TIME ZONE,
    motivo      VARCHAR(255),
    instante    TIMESTAMP(6) WITH TIME ZONE
);

CREATE TABLE registro_auditoria (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    entidade       VARCHAR(255),
    entidade_id    BIGINT,
    acao           VARCHAR(255),
    valor_anterior VARCHAR(1000),
    valor_novo     VARCHAR(1000),
    ator           VARCHAR(255),
    instante       TIMESTAMP(6) WITH TIME ZONE
);

CREATE INDEX registro_auditoria_entidade ON registro_auditoria (entidade, entidade_id, instante);

CREATE TABLE notificacao_outbox (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    evento       VARCHAR(255),
    destinatario VARCHAR(255),
    payload      VARCHAR(1000),
    estado       VARCHAR(255),
    tentativas   INTEGER NOT NULL
);

CREATE TABLE emprestimo (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    reserva_id    BIGINT,
    recurso_id    BIGINT,
    retirada_em   TIMESTAMP(6) WITH TIME ZONE,
    retirado_por  VARCHAR(255),
    devolvido_em  TIMESTAMP(6) WITH TIME ZONE,
    devolvido_por VARCHAR(255)
);
